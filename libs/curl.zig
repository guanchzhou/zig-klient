const Source = struct {
    b: *std.Build,
    dep: *std.Build.Dependency,
    root: []const u8,

    fn path(self: Source, sub: []const u8) std.Build.LazyPath {
        return self.dep.path(self.b.pathJoin(&.{ self.root, sub }));
    }
};

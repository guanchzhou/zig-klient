//! Static libcurl over mbedTLS, nghttp2 and zlib. The configure macros are
//! adapted from jiacai2050/zig-curl (MIT); nghttp2 support is added here.

const std = @import("std");

pub fn create(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    dep: *std.Build.Dependency,
    root: []const u8,
) *std.Build.Step.Compile {
    const src = Source{ .b = b, .dep = dep, .root = root };
    const lib = b.addLibrary(.{
        .linkage = .static,
        .name = "curl",
        .root_module = b.createModule(.{
            .target = target,
            .optimize = optimize,
            .link_libc = true,
        }),
    });
    const m = lib.root_module;
    inline for (srcs) |s| {
        m.addCSourceFile(.{ .file = src.path(s), .flags = &.{"-std=gnu99"} });
    }
    m.addIncludePath(src.path("lib"));
    m.addIncludePath(src.path("include"));
    lib.installHeadersDirectory(src.path("include/curl"), "curl", .{});

    for (common_macros) |name| m.addCMacro(name, "1");

    const os = target.result.os.tag;
    if (os.isDarwin()) {
        // USE_IPV6 on macOS turns on CURL_MACOS_CALL_COPYPROXIES, which needs the
        // CoreFoundation and SystemConfiguration frameworks; release builds
        // cross-compile from Linux without the macOS SDK.
        m.addCMacro("OS", "\"mac\"");
        m.addCMacro("CURL_OS", "\"mac\"");
    } else {
        for (linux_macros) |name| m.addCMacro(name, "1");
        m.addCMacro("USE_IPV6", "1");
        m.addCMacro("OS", "\"Linux\"");
        m.addCMacro("CURL_OS", switch (target.result.cpu.arch) {
            .x86_64 => "\"x86_64-pc-linux-gnu\"",
            .aarch64 => "\"aarch64-pc-linux-gnu\"",
            else => "\"Linux\"",
        });
    }

    m.addCMacro("CURL_EXTERN_SYMBOL", "__attribute__ ((__visibility__ (\"default\")))");
    m.addCMacro("RANDOM_FILE", "\"/dev/urandom\"");
    m.addCMacro("RECV_TYPE_ARG1", "int");
    m.addCMacro("RECV_TYPE_ARG2", "void *");
    m.addCMacro("RECV_TYPE_ARG3", "size_t");
    m.addCMacro("RECV_TYPE_ARG4", "int");
    m.addCMacro("RECV_TYPE_RETV", "ssize_t");
    m.addCMacro("SEND_QUAL_ARG2", "const");
    m.addCMacro("SEND_TYPE_ARG1", "int");
    m.addCMacro("SEND_TYPE_ARG2", "void *");
    m.addCMacro("SEND_TYPE_ARG3", "size_t");
    m.addCMacro("SEND_TYPE_ARG4", "int");
    m.addCMacro("SEND_TYPE_RETV", "ssize_t");
    m.addCMacro("SIZEOF_INT", "4");
    m.addCMacro("SIZEOF_SHORT", "2");
    m.addCMacro("SIZEOF_LONG", "8");
    m.addCMacro("SIZEOF_OFF_T", "8");
    m.addCMacro("SIZEOF_CURL_OFF_T", "8");
    m.addCMacro("SIZEOF_SIZE_T", "8");
    m.addCMacro("SIZEOF_TIME_T", "8");
    m.addCMacro("_FILE_OFFSET_BITS", "64");
    return lib;
}

